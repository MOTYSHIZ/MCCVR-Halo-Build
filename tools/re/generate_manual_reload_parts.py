"""Generate src/common/manual_reload_parts.generated.h from docs/RELOAD-CATALOG-EVIDENCE-2026-09-16.json.

For each Halo 3 / ODST first-person weapon render model in the official-kit evidence, the node index of the
magazine part (the node the reload catalogue selected) and of the part the hand works to chamber a round:
`ophandle` (the operating handle of the assault rifle, battle rifle and sniper rifle), `charging_handle` (the
SMGs), `slide` (the pistols), `pump` (the shotgun). Node order in the evidence is the render model's own node
order, so an index here is the palette's node index for that model (FpVisiblePaletteHook's boneMap index).

A weapon fed one round at a time has no magazine the catalogue selects; its `bullet` node (the shell the hand
carries into the loading port in its own reload animation: the shotgun's) stands in for it, so the learned reload
animation (reload_clip_logic.h) can find the shell's way in.

Run with --check to verify the checked-in header matches.
"""
from pathlib import Path
import json
import sys

ROOT = Path(__file__).resolve().parents[2]
EVIDENCE = ROOT / 'docs/RELOAD-CATALOG-EVIDENCE-2026-09-16.json'
OUT = ROOT / 'src/common/manual_reload_parts.generated.h'
RACK = {'ophandle': 'Handle', 'charging_handle': 'Handle', 'slide': 'Slide', 'pump': 'Pump'}


def build():
    rows = []
    for entry in json.loads(EVIDENCE.read_text()):
        if entry['title'] not in ('Halo3', 'Halo3ODST'):
            continue
        nodes = entry['nodes']
        mag = nodes.index(entry['selected'][0]) if entry['selected'] else -1
        if mag < 0 and 'pump' in nodes and 'bullet' in nodes:
            mag = nodes.index('bullet')
        rack, kind = -1, 'None'
        for name, k in RACK.items():
            if name in nodes:
                rack, kind = nodes.index(name), k
                break
        if mag < 0 and rack < 0:
            continue
        title = 'GameTitle::Halo3' if entry['title'] == 'Halo3' else 'GameTitle::Halo3ODST'
        rows.append((title, int(entry['identity'], 16), entry['name'], len(nodes), mag, rack, kind,
                     entry['source_tag']))
    rows.sort()
    lines = ['#pragma once',
             '// Generated by tools/re/generate_manual_reload_parts.py from docs/RELOAD-CATALOG-EVIDENCE-2026-09-16.json',
             '// (official H3EK / H3ODSTEK render models). Do not edit.',
             '#include "manual_reload_parts.h"',
             'namespace manual_reload {',
             'inline constexpr Parts kParts[]{']
    for title, identity, name, count, mag, rack, kind, tag in rows:
        lines.append(f'    {{{title},0x{identity:016X}ull,"{name}",{count},{mag},{rack},RackKind::{kind}}}, // {tag}')
    lines += ['};', '}', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    text = build()
    if '--check' in sys.argv:
        current = OUT.read_text() if OUT.exists() else ''
        if current.replace('\r\n', '\n') != text:
            sys.exit('manual_reload_parts.generated.h is out of date')
        print('manual_reload_parts.generated.h matches the evidence')
    else:
        OUT.write_text(text, newline='\n')
        print(f'wrote {OUT}')
