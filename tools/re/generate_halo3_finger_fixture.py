"""Generate the Halo 3 first-person bind fixture from the official H3EK export.

The export is not kept in the repository (out/ is ignored). To make it again:

    7z x <H3EK>/H3EK.7z -oout/h3ek-fp tags/objects/characters/masterchief/fp/fp.render_model
    (in out/h3ek-fp, with an empty data/ folder)
    <H3EK>/tool.exe export-tag-to-xml <that tag> h3_masterchief_fp_fp.render_model.xml

The export is SHA-pinned below; see docs/PLAYER-IK-PARITY-GAP-2026-11-13.md.
"""
from pathlib import Path
import hashlib
import xml.etree.ElementTree as ET

root = Path(__file__).resolve().parents[2]
path = root / 'out/h3ek-fp/h3_masterchief_fp_fp.render_model.xml'
digest = 'b85a4960c113e0a1b69287dbef38ed559342ae98f7277e0a46d50e6e38a54f99'
assert hashlib.sha256(path.read_bytes()).hexdigest() == digest, 'not the pinned H3EK export'
tag = ET.fromstring(path.read_text(encoding='utf-8', errors='replace').replace('value="<unavailable>"', 'value="unavailable"'))
nodes = []
for node in tag.find("block[@name='nodes']"):
    fields = {f.get('name'): f.get('value') for f in node.findall('field')}
    nodes.append((node.get('name'), int(fields['parent node'].split(',')[-1]),
                  fields['default translation'].split(',') + fields['default rotation'].split(',')))
assert len(nodes) == 37
checksum = next(f.get('value') for f in tag.iter('field') if f.get('name') == 'runtime import info checksum')
assert checksum == '504041493'
lines = ['#pragma once', '// Generated by tools/re/generate_halo3_finger_fixture.py from the SHA-pinned official',
         '// H3EK export of objects/characters/masterchief/fp/fp.render_model (checksum 504041493).',
         '// Default translation (3) then default rotation quaternion (4), per node, parent-relative.',
         'inline constexpr float Halo3FpBindLocal[37][7]{']
for name, parent, values in nodes:
    values = [x if ('.' in x or 'e' in x.lower()) else x + '.0' for x in values]
    lines.append('    {' + ','.join(x + 'f' for x in values) + '}, // ' + name)
lines += ['};', 'inline constexpr int16_t Halo3FpBindParents[37]{' + ','.join(str(x[1]) for x in nodes) + '};',
          'inline constexpr const char* Halo3FpBindNames[37]{' + ','.join('"' + x[0] + '"' for x in nodes) + '};', '']
(root / 'tests/halo3_finger_bind_fixture.h').write_text('\n'.join(lines))
print('Verified the pinned H3EK export; generated the 37-node Halo 3 bind fixture')
